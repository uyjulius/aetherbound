/**
 * Record that a prop was made here rather than bought.
 *
 *   node tools/mark-generated.mjs chest barrel crate
 *
 * `fetch-props.mjs` writes a manifest entry for every model it downloads, and shipping a
 * generated mesh over the top of one leaves that entry behind: the file is this project's own
 * and the manifest still names an artist, a licence and a poly.pizza URL. The credits screen
 * reads the manifest, so the lie reaches the player.
 *
 * This rewrites the entry to what is true — generated here, from its own concept view — and
 * re-measures the file, because `plan-scenery.mjs` places a prop from `size` and `base` and the
 * new mesh is not the shape of the old one. `CREDITS.md` is moved in the same pass: the prop
 * leaves the bought table and joins the generated one. Both are done together because they are
 * one fact, and `scenery-parity.mjs` compares them — it was what noticed the first seven props
 * had been replaced and still read as somebody else's work.
 */

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(new URL('../package.json', import.meta.url)));
const say = (s = '') => console.log(s);

const ATTRIBUTION = 'Generated by this project: a concept view from FLUX.1-schnell, '
  + 'reconstructed by Hunyuan3D-2.1, cleaned and decimated in Blender.';

const ids = process.argv.slice(2).filter((a) => !a.startsWith('-'));
if (!ids.length) {
  say('Usage: node tools/mark-generated.mjs <id> [id …]');
  process.exit(1);
}

const manifestPath = path.join(root, 'godot', 'assets', 'props', 'manifest.json');
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
const trouble = [];
const moved = [];

for (const id of ids) {
  const file = `${id}.glb`;
  const full = path.join(root, 'godot', 'assets', 'props', file);
  if (!fs.existsSync(full)) {
    trouble.push(`${id}: no model at ${path.relative(root, full)}`);
    continue;
  }
  const concept = path.join('assets', 'concepts', `${id}-front.png`);
  if (!fs.existsSync(path.join(root, concept))) {
    // Without the concept there is nothing to point at, and an entry that claims to be
    // generated but cannot say from what is no better than the one it replaced.
    trouble.push(`${id}: no concept view at ${concept}`);
    continue;
  }
  const measured = JSON.parse(execFileSync('python3',
    [path.join(root, 'tools', 'measure_glb.py'), full], { encoding: 'utf8' }))[file];
  const before = manifest[id] ?? {};
  manifest[id] = {
    file,
    id: null,
    title: before.title ?? id,
    author: 'generated for this game',
    licence: 'generated',
    attribution: ATTRIBUTION,
    source: concept,
    ...measured,
    bytes: fs.statSync(full).size,
  };
  say(`  ${id.padEnd(20)} ${(before.author ?? 'new').padEnd(12)} → generated  `
    + `${measured.size.map((n) => n.toFixed(2)).join(' × ')}`);
  moved.push({ id, title: manifest[id].title, concept });
}

if (trouble.length) {
  say();
  say(`\x1b[31mFAIL\x1b[0m — ${trouble.length} could not be marked:`);
  for (const line of trouble) say(`  ${line}`);
  process.exit(1);
}
fs.writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 1)}\n`);

// And the credits, which are the half a player can see. The file has two tables — what was
// downloaded and what was made here — and a prop that moved between them has to move in the
// file too, or the game credits an artist for a model of its own.
const creditsPath = path.join(root, 'godot', 'assets', 'props', 'CREDITS.md');
const HEADING = '## Generated for this game';
const credits = fs.readFileSync(creditsPath, 'utf8');
const cut = credits.indexOf(HEADING);
if (cut < 0) {
  say(`\x1b[31mFAIL\x1b[0m — no "${HEADING}" section in ${path.relative(root, creditsPath)}`);
  process.exit(1);
}
const bought = credits.slice(0, cut).split('\n');
const made = credits.slice(cut).split('\n');
for (const entry of moved) {
  const row = `| ${entry.id} | ${entry.title} | generated for this game | generated `
    + `| ${entry.concept} |`;
  const isRow = (line, id) => line.startsWith(`| ${id} |`);
  const from = bought.findIndex((line) => isRow(line, entry.id));
  if (from >= 0) bought.splice(from, 1);
  const existing = made.findIndex((line) => isRow(line, entry.id));
  if (existing >= 0) {
    made[existing] = row;
    continue;
  }
  // Into the table, not onto the end of the section. A section ends in prose and blank lines,
  // and a row appended there is a row outside the table — which renders as a stray line and
  // reads, to anything parsing the file, as no row at all.
  let end = made.findIndex((line) => line.startsWith('|---')) + 1;
  while (end < made.length && made[end].startsWith('| ')) end++;
  made.splice(end, 0, row);
}
// Alphabetical, as both tables already are — the rows are appended above and a table that
// sorts itself is one nobody has to remember to sort.
const sortRows = (lines) => {
  const first = lines.findIndex((line) => line.startsWith('|---'));
  if (first < 0) return lines;
  let last = first + 1;
  while (last < lines.length && lines[last].startsWith('| ')) last++;
  return [...lines.slice(0, first + 1),
    ...lines.slice(first + 1, last).sort((a, b) => a.localeCompare(b)),
    ...lines.slice(last)];
};
fs.writeFileSync(creditsPath, `${[...sortRows(bought), ...sortRows(made)].join('\n')
  .replace(/\n+$/, '')}\n`);
say();
say(`\x1b[32mOK\x1b[0m — ${ids.length} prop(s) now say where they came from, in the manifest `
  + 'and in the credits. Run `npm run scenery` to re-place them.');
